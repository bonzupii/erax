/// Process-wide ort environment, mirroring floravox-core's own
/// OnceLock: sessions hold weak references, so the environment must
/// outlive every session.
fn ort_env() -> Result<&'static ort::environment::Environment, SynthesizeError> {
    static ENV: OnceLock<Result<ort::environment::Environment, ort::Error>> = OnceLock::new();
    ENV.get_or_init(|| ort::init().build())
        .as_ref()
        .map_err(|e| SynthesizeError::ModelLoad(format!("ort environment: {e}")))
}

/// Parse a raw voice bank into rows of 256 f32.
#[cfg(speech_provisioned)]
fn parse_bank(bytes: &[u8], voice: VoiceId) -> Result<Vec<Vec<f32>>, SynthesizeError> {
    if bytes.len() % (STYLE_DIM * 4) != 0 {
        return Err(SynthesizeError::ModelLoad(format!(
            "voice {} bank size {} is not a whole number of {STYLE_DIM}-float rows",
            voice.file_stem(),
            bytes.len()
        )));
    }
    let floats: Vec<f32> = bytes
        .chunks_exact(4)
        .map(|c| f32::from_le_bytes([c[0], c[1], c[2], c[3]]))
        .collect();
    Ok(floats.chunks_exact(STYLE_DIM).map(<[f32]>::to_vec).collect())
}

/// The embedded-weights Kokoro backend.
pub struct EmbeddedKokoroBackend {
    session: ort::session::Session,
    config: ResolvedConfig,
    banks: HashMap<VoiceId, Vec<Vec<f32>>>,
    current: VoiceId,
    input_tokens: String,
    input_style: String,
    input_speed: String,
    output_audio: String,
    has_durations: bool,
}

impl EmbeddedKokoroBackend {
    /// Build from the embedded weights. Verifies the ONNX input
    /// names against the expected kokoro signature; an export with
    /// different names fails typed here, not silently at first
    /// synthesis.
    pub fn new(voice: VoiceId) -> Result<Self, SynthesizeError> {
        #[cfg(not(speech_provisioned))]
        {
            let _ = voice;
            return Err(SynthesizeError::ModelLoad(
                "kokoro weights were not provisioned by build.rs".into(),
            ));
        }
        #[cfg(speech_provisioned)]
        {
            Self::new_provisioned(voice)
        }
    }

    #[cfg(speech_provisioned)]
    fn new_provisioned(voice: VoiceId) -> Result<Self, SynthesizeError> {
        let env = ort_env()?;
        let session = ort::session::Session::builder(env)
            .map_err(|e| SynthesizeError::ModelLoad(format!("ort session builder: {e}")))?
            .commit_from_memory(KOKORO_MODEL)
            .map_err(|e| SynthesizeError::ModelLoad(format!("kokoro model load: {e}")))?;

        let input_names: Vec<String> =
            session.inputs().iter().map(|i| i.name().to_string()).collect();
        let find = |want: &[&str]| {
            input_names
                .iter()
                .find(|n| want.contains(&n.as_str()))
                .cloned()
        };
        // The onnx-community export names the token input "tokens"
        // (some exports call it "input_ids"); style/speed are stable.
        let input_tokens = find(&["tokens", "input_ids"]).ok_or_else(|| {
            SynthesizeError::ModelLoad(format!(
                "kokoro model inputs {input_names:?} lack a token input"
            ))
        })?;
        let input_style = find(&["style"]).ok_or_else(|| {
            SynthesizeError::ModelLoad(format!(
                "kokoro model inputs {input_names:?} lack a style input"
            ))
        })?;
        let input_speed = find(&["speed"]).ok_or_else(|| {
            SynthesizeError::ModelLoad(format!(
                "kokoro model inputs {input_names:?} lack a speed input"
            ))
        })?;
        let output_names: Vec<String> =
            session.outputs().iter().map(|o| o.name().to_string()).collect();
        // The onnx-community export names the waveform output
        // "waveform" (some exports call it "audio").
        let output_audio = output_names
            .iter()
            .find(|n| n.as_str() == "audio" || n.as_str() == "waveform")
            .cloned()
            .ok_or_else(|| {
                SynthesizeError::ModelLoad(format!(
                    "kokoro model outputs {output_names:?} lack an audio output"
                ))
            })?;
        let has_durations = output_names.iter().any(|n| n == "durations");

        let mut banks = HashMap::with_capacity(VoiceId::ALL.len());
        for v in VoiceId::ALL {
            banks.insert(v, parse_bank(voice_bank_bytes(v), v)?);
        }
        if !banks.contains_key(&voice) {
            return Err(SynthesizeError::ModelLoad(format!(
                "voice {} has no provisioned bank",
                voice.file_stem()
            )));
        }

        let mut phoneme_id_map: HashMap<String, Vec<i64>> =
            HashMap::with_capacity(KOKORO_PHONEME_IDS.len());
        for (sym, id) in KOKORO_PHONEME_IDS {
            phoneme_id_map.insert(sym.to_string(), vec![*id]);
        }
        let config = ResolvedConfig {
            sample_rate: KOKORO_SAMPLE_RATE,
            hop_length: 600,
            phoneme_id_map,
            noise_scale: 0.667,
            length_scale: 1.0,
            noise_scale_w: 0.8,
            speaker_id: Some(0),
            has_durations,
            uses_scales: false,
            framing: ControlSymbols::kokoro(),
            is_char_table: false,
        };
        let backend = Self {
            session,
            config,
            banks,
            current: voice,
            input_tokens,
            input_style,
            input_speed,
            output_audio,
            has_durations,
        };
        Ok(backend)
    }
}

impl VoiceBackend for EmbeddedKokoroBackend {
    fn config(&self) -> &ResolvedConfig {
        &self.config
    }

    fn set_speaker(&mut self, id: i64) {
        if let Ok(i) = usize::try_from(id) {
            if let Some(voice) = VoiceId::from_index(i) {
                self.current = voice;
            }
        }
    }

    fn speaker_count(&self) -> Option<usize> {
        Some(VoiceId::ALL.len())
    }

    fn run(&mut self, ids: &[i64], length_scale: f32) -> anyhow::Result<(Vec<f32>, Option<Vec<i64>>)> {
        // Mirrors floravox-core 0.8.8 KokoroBackend::run (Apache-2.0/MIT):
        // speed divides durations, so speed = 1/length_scale keeps the
        // trait's rate contract.
        let speed = (1.0 / length_scale.max(0.1)).clamp(0.1, 10.0);
        let bank = self.banks.get(&self.current).ok_or_else(|| {
            anyhow::anyhow!("no bank for voice {}", self.current.file_stem())
        })?;
        // Length-conditioned style row (sherpa-onnx semantics): the
        // row index is the unpadded token count, clamped to the bank.
        let row = bank[ids.len().min(bank.len() - 1)].clone();

        let seq = i64::try_from(ids.len())
            .map_err(|_| anyhow::anyhow!("kokoro token sequence too long"))?;
        let tokens = ort::value::Tensor::from_array((vec![1_i64, seq], ids.to_vec()))
            .map_err(|e| anyhow::anyhow!("kokoro tokens tensor: {e}"))?;
        let style_tensor =
            ort::value::Tensor::from_array((vec![1_i64, STYLE_DIM as i64], row))
                .map_err(|e| anyhow::anyhow!("kokoro style tensor: {e}"))?;
        let speed_tensor = ort::value::Tensor::from_array((vec![1_i64], vec![speed]))
            .map_err(|e| anyhow::anyhow!("kokoro speed tensor: {e}"))?;

        let inputs: Vec<(String, ort::session::SessionInputValue<'_>)> = vec![
            (self.input_tokens.clone(), tokens.into()),
            (self.input_style.clone(), style_tensor.into()),
            (self.input_speed.clone(), speed_tensor.into()),
        ];
        let outputs = self
            .session
            .run(inputs)
            .map_err(|e| anyhow::anyhow!("kokoro inference: {e}"))?;

        let mut audio: Vec<f32> = Vec::new();
        let mut durations: Option<Vec<i64>> = None;
        for (name, output) in &outputs {
            if name == &self.output_audio {
                let view = output
                    .try_extract_tensor::<f32>()
                    .map_err(|e| anyhow::anyhow!("kokoro audio extract: {e}"))?;
                audio = view.1.to_vec();
            } else if self.has_durations && name == "durations" {
                let view = output
                    .try_extract_tensor::<f32>()
                    .map_err(|e| anyhow::anyhow!("kokoro durations extract: {e}"))?;
                durations = Some(view.1.iter().map(|&f| f.round() as i64).collect());
            }
        }
        if audio.is_empty() {
            return Err(anyhow::anyhow!("kokoro model produced no audio output"));
        }
        Ok((audio, durations))
    }
}

/// Linear-interpolation resampler for the fixed 24 kHz to 16 kHz
/// step. Announcement speech tolerates this fine; a higher-quality
/// resampler would be measurable overkill for the interface rate.
fn resample_24k_to_16k(input: &[f32]) -> Pcm16k {
    if input.is_empty() {
        return Vec::new();
    }
    let out_len = (input.len() * PCM16K_SAMPLE_RATE as usize) / KOKORO_SAMPLE_RATE as usize;
    let mut out = Vec::with_capacity(out_len);
    for i in 0..out_len {
        let pos = i as f32 * KOKORO_SAMPLE_RATE as f32 / PCM16K_SAMPLE_RATE as f32;
        let i0 = pos.floor() as usize;
        let i1 = (i0 + 1).min(input.len() - 1);
        let frac = pos - i0 as f32;
        out.push(input[i0] * (1.0 - frac) + input[i1] * frac);
    }
    out
}

/// Split text into sentence spans on terminal punctuation. Naive by
/// design (abbreviations can split early); the chunks stay in order
/// and nothing is dropped or reordered.
fn split_sentences(text: &str) -> Vec<&str> {
    let mut out = Vec::new();
    let mut start = 0;
    let bytes = text.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        let c = bytes[i];
        if matches!(c, b'.' | b'!' | b'?') {
            let end = i + 1;
            let piece = text[start..end].trim();
            if !piece.is_empty() {
                out.push(piece);
            }
            start = end;
        }
        i += 1;
    }
    let tail = text[start..].trim();
    if !tail.is_empty() {
        out.push(tail);
    }
    out
}

/// Built-in speech synthesizer: one floravox `Synthesizer` driving
/// the embedded-weights backend. Voice switches go through
/// `Synthesizer::set_speaker`, which forwards to the backend's
/// `VoiceBackend::set_speaker`.
pub struct KokoroSynthesizer {
    synth: Synthesizer<floravox_g2p::MisakiG2p>,
    voice: VoiceId,
}

impl KokoroSynthesizer {
    /// Build the synthesizer for one voice. Loads every provisioned
    /// voice bank (~29 MiB); switching voices afterwards is free.
    pub fn new(voice: VoiceId) -> Result<Self, SynthesizeError> {
        let index = VoiceId::ALL
            .iter()
            .position(|v| *v == voice)
            .and_then(|i| i64::try_from(i).ok())
            .ok_or_else(|| {
                SynthesizeError::ModelLoad(format!("voice {} is not provisioned", voice.file_stem()))
            })?;
        let backend: Box<dyn VoiceBackend> = Box::new(EmbeddedKokoroBackend::new(voice)?);
        // Rust-native phonemization at both levels: the document
        // pre-pass and the token fallback are misaki-rs, with its
        // espeak fallback disabled (the `false` argument).
        let synth = Synthesizer::new(backend, floravox_g2p::MisakiG2p::new(false))
            .with_document_phonemizer(Box::new(floravox_core::MisakiPrePass(
                floravox_g2p::MisakiG2p::new(false),
            )));
        synth
            .set_speaker(index)
            .map_err(|e| SynthesizeError::ModelLoad(format!("kokoro set_speaker: {e:#}")))?;
        Ok(Self { synth, voice })
    }
}

impl SpeechSynthesizer for KokoroSynthesizer {
    fn synthesize(&mut self, text: &str) -> Result<SynthesisStream, SynthesizeError> {
        if text.trim().is_empty() {
            return Ok(SynthesisStream {
                chunks: Vec::new(),
                first_audio_latency_ms: 0,
            });
        }
        let mut chunks = Vec::new();
        let mut first_latency = 0;
        for (n, sentence) in split_sentences(text).iter().enumerate() {
            let t0 = Instant::now();
            let (audio_24k, _events, _rate) = self
                .synth
                .synthesize(sentence)
                .map_err(|e| SynthesizeError::Inference(format!("kokoro synthesize: {e:#}")))?;
            let latency_ms = u64::try_from(t0.elapsed().as_millis()).unwrap_or(u64::MAX);
            if n == 0 {
                first_latency = latency_ms;
            }
            let pcm = resample_24k_to_16k(&audio_24k);
            if !pcm.is_empty() {
                chunks.push(pcm);
            }
        }
        Ok(SynthesisStream {
            chunks,
            first_audio_latency_ms: first_latency,
        })
    }

    fn set_voice(&mut self, voice: VoiceId) -> Result<(), SynthesizeError> {
        let index = VoiceId::ALL
            .iter()
            .position(|v| *v == voice)
            .and_then(|i| i64::try_from(i).ok())
            .ok_or(SynthesizeError::Unsupported)?;
        self.synth
            .set_speaker(index)
            .map_err(|e| SynthesizeError::Inference(format!("kokoro set_speaker: {e:#}")))?;
        self.voice = voice;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn resample_shortens_by_two_thirds() {
        let input: Vec<f32> = (0..2400).map(|i| i as f32).collect();
        let out = resample_24k_to_16k(&input);
        assert_eq!(out.len(), 1600);
        assert!((out[0] - 0.0).abs() < 1e-6);
    }

    #[test]
    fn resample_empty_stays_empty() {
        assert!(resample_24k_to_16k(&[]).is_empty());
    }

    #[test]
    fn split_sentences_keeps_everything_in_order() {
        let parts = split_sentences("Hello world. How are you? Fine!");
        assert_eq!(parts, vec!["Hello world.", "How are you?", "Fine!"]);
        let single = split_sentences("no terminal punctuation");
        assert_eq!(single, vec!["no terminal punctuation"]);
        assert!(split_sentences("   ").is_empty());
    }

    #[test]
    #[cfg(speech_provisioned)]
    fn phoneme_table_has_expected_shape() {
        let map: HashMap<&str, i64> = KOKORO_PHONEME_IDS.iter().copied().collect();
        // No duplicate symbols; ids are positive (0 is the pad token,
        // never in the map).
        assert_eq!(map.len(), KOKORO_PHONEME_IDS.len());
        assert!(map.values().all(|&id| id > 0));
        // The word separator must exist (kokoro framing is space-only).
        assert!(map.contains_key(" "));
    }

    #[test]
    fn voice_id_all_covers_every_variant() {
        assert_eq!(VoiceId::ALL.len(), 55);
        for (i, v) in VoiceId::ALL.iter().enumerate() {
            assert_eq!(VoiceId::from_index(i), Some(*v));
            assert!(!v.file_stem().is_empty());
        }
        assert_eq!(VoiceId::from_index(55), None);
    }
}
