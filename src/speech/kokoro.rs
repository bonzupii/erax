//! Built-in TTS: Kokoro-82M int8 via floravox-core with a Rust-native phonemizer.
//!
//! floravox-core's own `KokoroBackend` loads voices from paths; this
//! module implements the same public `VoiceBackend` trait over the
//! embedded weights (model bytes, per-voice style banks, phoneme
//! map), so nothing is read from disk at runtime. Text handling —
//! G2P via misaki-rs (dictionaries compiled in), SSML, word timings —
//! stays in floravox's `Synthesizer`, which drives this backend.
//!
//! espeak-ng is nowhere in the dependency tree (verified by license
//! audit); the phonemizer is misaki-rs with its espeak fallback
//! disabled.

